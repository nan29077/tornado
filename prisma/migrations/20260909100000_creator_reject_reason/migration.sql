-- 심사 반려·정지 사유 저장.
--
-- 왜 필요한가
--   크리에이터 상태 안내 화면은 "사유 확인은 고객센터로" 라고 안내하지만, 정작 사유를
--   담을 컬럼이 없어 관리자가 남긴 판단 근거가 어디에도 저장되지 않았다. 반려된 사람은
--   무엇을 고쳐야 재신청할 수 있는지 알 수 없고, 관리자도 왜 반려했는지 되짚을 수 없다.
--
--   승인으로 되돌아갈 때는 NULL 로 지운다(애플리케이션에서 처리). 옛 반려 사유가
--   승인된 채널에 남아 있으면 안 된다.
ALTER TABLE "creator_profile" ADD COLUMN IF NOT EXISTS "reject_reason" TEXT;
